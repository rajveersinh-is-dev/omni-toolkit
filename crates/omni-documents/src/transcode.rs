use omni_core::{
    async_trait, DataPayload, DataType, ExecutionContext, OmniError, OmniResult, Operation,
    OperationCategory, OperationManifest,
};
use pulldown_cmark::{html, Options, Parser};
use serde_json::Value;

pub struct DocumentTranscodeOp;

#[async_trait]
impl Operation for DocumentTranscodeOp {
    fn manifest(&self) -> OperationManifest {
        OperationManifest::new(
            "doc.transcode",
            "Document Transcoder",
            "Transcodes documents between Markdown (GFM), HTML5, LaTeX, and Man pages",
            OperationCategory::DocumentsAndMedia,
        )
        .with_types(vec![DataType::Text], vec![DataType::Text])
    }

    async fn execute(&self, input: DataPayload, config: Value, _ctx: &ExecutionContext) -> OmniResult<DataPayload> {
        let from = config.get("from").and_then(|v| v.as_str()).unwrap_or("markdown");
        let to = config.get("to").and_then(|v| v.as_str()).unwrap_or("html");
        let text = input.into_text()?;

        if from == "markdown" || from == "md" {
            let mut options = Options::empty();
            options.insert(Options::ENABLE_TABLES);
            options.insert(Options::ENABLE_FOOTNOTES);
            options.insert(Options::ENABLE_STRIKETHROUGH);
            options.insert(Options::ENABLE_TASKLISTS);

            let parser = Parser::new_ext(&text, options);

            match to {
                "html" => {
                    let mut html_output = String::new();
                    html::push_html(&mut html_output, parser);
                    Ok(DataPayload::text(html_output))
                }
                "latex" => {
                    // Converts markdown elements to basic LaTeX commands
                    let mut latex = String::new();
                    latex.push_str("% Generated by OMNI Document Transcoder\n");
                    for line in text.lines() {
                        if line.starts_with("# ") {
                            latex.push_str(&format!("\\section{{{}}}\n", &line[2..]));
                        } else if line.starts_with("## ") {
                            latex.push_str(&format!("\\subsection{{{}}}\n", &line[3..]));
                        } else if line.starts_with("### ") {
                            latex.push_str(&format!("\\subsubsection{{{}}}\n", &line[4..]));
                        } else if line.trim().is_empty() {
                            latex.push('\n');
                        } else {
                            latex.push_str(&format!("{}\n", line));
                        }
                    }
                    Ok(DataPayload::text(latex))
                }
                "man" => {
                    let mut man = String::new();
                    man.push_str(".TH OMNI 1 \"November 2026\" \"OMNI Toolkit\"\n");
                    for line in text.lines() {
                        if line.starts_with("# ") {
                            man.push_str(&format!(".SH {}\n", &line[2..].to_uppercase()));
                        } else if line.starts_with("## ") {
                            man.push_str(&format!(".SS {}\n", &line[3..]));
                        } else {
                            man.push_str(&format!("{}\n", line));
                        }
                    }
                    Ok(DataPayload::text(man))
                }
                _ => Err(OmniError::Validation(format!("Unsupported target document format '{to}'"))),
            }
        } else {
            Err(OmniError::Validation(format!("Unsupported source document format '{from}'")))
        }
    }
}
